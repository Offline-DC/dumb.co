#!/usr/bin/env python3
"""
Trace the screen aperture out of assets/flipphone.png and write it into
build/parts/18_quiz.css as a clip-path.

The handset art is hand-drawn: the screen opening is a wobbly quadrilateral,
not a rectangle. The CSS used to approximate it with a plain box, which sat
slightly inside the ink and left a hairline of yellow between the screen fill
and the drawn stroke. This measures the real opening instead.

How it works: the art is black strokes on transparency, and the screen is a
hole in it. So the aperture is simply the transparent region you land in if
you start in the middle of the screen -- no guessing, no eyeballing.

Run after changing assets/flipphone.png:

    python3 build/trace_screen.py && python3 build/build.py

Needs PIL, numpy, cv2 (all already used elsewhere in this build).
"""
import sys, pathlib
import numpy as np
from PIL import Image
import cv2

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from make_dpad_arrows import ARROW_ART_W   # one source of truth for arrow size

ROOT  = pathlib.Path(__file__).resolve().parent.parent
ART   = ROOT / "assets" / "flipphone_bigscreen.png"   # built by expand_screen.py
CSS   = ROOT / "build" / "parts" / "18_quiz.css"
KEYCSS= ROOT / "build" / "parts" / "22_snake.css"
KSTART= "  /* >>> dpad: generated by build/trace_screen.py, do not hand-edit */"
KEND  = "  /* <<< dpad */"
JS    = ROOT / "build" / "parts" / "30_phone.js"
JSTART= "  /* >>> art: generated by build/trace_screen.py, do not hand-edit */"
JEND  = "  /* <<< art */"
START = "  /* >>> screen-shape: generated by build/trace_screen.py, do not hand-edit */"
END   = "  /* <<< screen-shape */"
EPS   = 1.0   # px of contour simplification: keeps the wobble, drops the jaggies


def must(cond, msg):
    if not cond:
        sys.exit("TRACE FAILED: " + msg)


def main():
    must(ART.exists(), f"{ART} missing")
    im = Image.open(ART).convert("RGBA")
    W, H = im.size
    alpha = np.array(im)[..., 3]

    # every non-ink pixel; the screen hole is one connected piece of this
    holes = (alpha <= 128).astype(np.uint8)
    n, lab = cv2.connectedComponents(holes, connectivity=4)
    must(n > 2, "no enclosed regions found - is the art still line-on-transparent?")

    # seed in the middle of the upper half, where the screen is
    sy, sx = int(H * 0.255), int(W * 0.50)
    rid = int(lab[sy, sx])
    must(rid != 0, "seed point landed on ink, not inside the screen")

    # the region must not touch the border, or we've flood-filled the background
    mask = (lab == rid).astype(np.uint8)
    touches = mask[0, :].any() or mask[-1, :].any() or mask[:, 0].any() or mask[:, -1].any()
    must(not touches, "traced region reaches the image edge - that's the background, not the screen")

    # close any speckles inside the aperture so the outline is a single loop
    ff = mask.copy()
    pad = np.zeros((H + 2, W + 2), np.uint8)
    cv2.floodFill(ff, pad, (0, 0), 1)          # fill from outside the shape
    mask = mask | (1 - ff)                      # anything unreached was an interior hole

    cnts, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    must(len(cnts) >= 1, "no contour")
    c = max(cnts, key=cv2.contourArea)

    x, y, w, h = cv2.boundingRect(c)
    frac = (w * h) / float(W * H)
    must(0.02 < frac < 0.25, f"aperture is {frac:.1%} of the art - that doesn't look like a screen")

    ap = cv2.approxPolyDP(c, EPS, True).reshape(-1, 2)
    must(len(ap) >= 4, "simplified to fewer than 4 points")

    # the element is the aperture's bounding box; clip-path points are % of it
    pts = [((px - x) / w * 100.0, (py - y) / h * 100.0) for px, py in ap]
    # every vertex is comma-separated; the line breaks are only for readability.
    # (joining a group of vertices with spaces instead makes the whole polygon
    # invalid and the browser silently computes clip-path:none.)
    vert = [f"{u:.2f}% {v:.2f}%" for u, v in pts]
    poly = ",\n      ".join(", ".join(vert[i:i + 4]) for i in range(0, len(vert), 4))

    # How far the drawn edge wanders inward, left and right. Anything laid out
    # as a rectangle -- a menu row, its highlight -- has to stay inside the
    # WORST of that excursion, or the clip-path shears it flat wherever the ink
    # bows in and leaves a yellow wedge wherever it bows out. That is what made
    # the selected row look like it was fighting the screen outline.
    # only the side runs: the polygon also traces the top and bottom edges,
    # whose vertices span the full width and would swamp the maximum.
    sides = [(u, v) for u, v in pts if 12 < v < 88]
    inset = max(max((u for u, _ in sides if u < 50), default=0),
                100 - min((u for u, _ in sides if u >= 50), default=100)) + 1.5

    block = f"""{START}
  /* {len(ap)} points traced from the {W}x{H} art at {EPS}px tolerance.
     The box is the aperture's exact bounding box; the clip-path follows the
     inside of the drawn stroke, so the screen fill stops where the ink starts
     instead of leaving a gap. */
  .phone-frame .pf-screen{{
    position:absolute; z-index:1;
    left:{100*x/W:.2f}%; top:{100*y/H:.2f}%; width:{100*w/W:.2f}%; height:{100*h/H:.2f}%;
    background:var(--yellow); overflow:hidden;
    box-shadow:inset 0 0 5px rgba(0,0,0,.35);
    /* the widest the drawn edge bows inward, plus a little air; anything
       rectangular inside the screen keeps clear of the ink by this much */
    --screen-inset:{inset:.2f}%;
    clip-path:polygon(
      {poly}
    );
  }}
{END}"""

    css = CSS.read_text(encoding="utf-8")
    must(css.count(START) == 1 and css.count(END) == 1,
         f"markers not found exactly once in {CSS.name} - add them around the .pf-screen rule")
    head = css[:css.index(START)]
    tail = css[css.index(END) + len(END):]
    CSS.write_text(head + block + tail, encoding="utf-8")

    # ---- the OK circle, so the d-pad follows the art too --------------
    best = None
    for rid in range(1, n):
        ys, xs = np.where(lab == rid)
        if len(ys) < 2000:
            continue
        y0, y1, x0, x1 = ys.min(), ys.max(), xs.min(), xs.max()
        if y0 < H * 0.45 or x0 == 0 or y0 == 0 or x1 == W - 1 or y1 == H - 1:
            continue
        bw, bh = x1 - x0 + 1, y1 - y0 + 1
        if not (0.8 < bw / bh < 1.25):      # round-ish: a hand-drawn circle
            continue
        # ...and the right SIZE. Once the number keys are cropped off, the
        # whole keypad interior is itself an enclosed round-ish region and it
        # is far bigger, so "largest round thing" picks the wrong one. The OK
        # circle is about 15% of the art's width; nothing else in that band is.
        if not (0.08 < bw / W < 0.22):
            continue
        if best is None or len(ys) > best[0]:
            best = (len(ys), x0, x1, y0, y1, bw, bh)
    must(best is not None, "couldn't find the OK circle - is the keypad still drawn?")
    _, kx0, kx1, ky0, ky1, kw, kh = best
    kcx, kcy = (kx0 + kx1) / 2, (ky0 + ky1) / 2
    # 0.79 = radius 32.5 of 41, the middle of the clear span on the LEFT axis
    # (24..41 -- the O's outer stroke to the ring). That side is the tightest,
    # and putting all four on one radius is what makes it read as a ring
    # rather than four separately placed marks. See ARROW_ART_W in
    # make_dpad_arrows.py for the measurements this comes from.
    # 24 artwork px wide -- build/make_dpad_arrows.py draws the chevron to
    # that width, and it is the widest one that still frames the "OK" at this
    # radius without touching the lettering.
    AW = ARROW_ART_W
    RING = 0.79
    def pos(dx, dy):
        return (100 * (kcx + dx * kw / 2) / W, 100 * (kcy + dy * kh / 2) / H)
    ks = {name: pos(dx, dy) for name, (dx, dy) in {
        "k-up": (0, -RING), "k-right": (RING, 0),
        "k-down": (0, RING), "k-left": (-RING, 0), "k-ok": (0, 0)}.items()}

    kblock = f"""{KSTART}
  /* The OK circle measured off {ART.name}: interior x[{kx0},{kx1}] y[{ky0},{ky1}],
     so it centres at {100*kcx/W:.2f}% / {100*kcy/H:.2f}%. Arrows sit at {int(RING*100)}% of that
     radius -- on the ring, framing the drawn "OK" instead of covering it.
     The four ovals around the circle are decoration: in the raw art they hold
     plain dashes, not arrows. */
  .phone-frame .pf-keys .k-up   {{left:{ks['k-up'][0]:.2f}%; top:{ks['k-up'][1]:.2f}%;}}
  .phone-frame .pf-keys .k-right{{left:{ks['k-right'][0]:.2f}%; top:{ks['k-right'][1]:.2f}%;}}
  .phone-frame .pf-keys .k-down {{left:{ks['k-down'][0]:.2f}%; top:{ks['k-down'][1]:.2f}%;}}
  .phone-frame .pf-keys .k-left {{left:{ks['k-left'][0]:.2f}%; top:{ks['k-left'][1]:.2f}%;}}
  .phone-frame .pf-keys .k-ok   {{left:{ks['k-ok'][0]:.2f}%; top:{ks['k-ok'][1]:.2f}%;
    width:5.7cqw; height:5.7cqw; min-width:34px; min-height:34px; font-size:0;}}
  /* The glyph is sized separately from the hit target. The target keeps a 34px
     floor so it stays clickable; the drawing must not, because a stroke is a
     fixed width in the artwork, and an arrow that stops shrinking with the
     handset ends up drawn in a different weight from every line around it --
     which is why these read as chunky on the desktop cameo and right on a
     phone. {AW}px of a {W}px-wide drawing, so the pen matches at any size. */
  .phone-frame .pf-keys button{{background-size:{100*AW/W:.2f}cqw {100*AW/W:.2f}cqw;}}
{KEND}"""
    kcss = KEYCSS.read_text(encoding="utf-8")
    must(kcss.count(KSTART) == 1 and kcss.count(KEND) == 1,
         f"dpad markers not found exactly once in {KEYCSS.name}")
    KEYCSS.write_text(
        kcss[:kcss.index(KSTART)] + kblock + kcss[kcss.index(KEND) + len(KEND):],
        encoding="utf-8")

    # ---- the numbers the layout code needs, from the same measurement ----
    drawn = np.where(alpha > 128)
    dy0, dy1 = int(drawn[0].min()), int(drawn[0].max())
    dx0, dx1 = int(drawn[1].min()), int(drawn[1].max())
    jblock = f"""{JSTART}
  /* Measured off {ART.name} ({W}x{H}) by build/trace_screen.py. These drive
     how big the handset is drawn on a phone, so they have to follow the art:
     when the drawing was shortened these were still the old ones and the
     handset kept sizing itself to a height it no longer had. */
  const ART = {{
    ratio: {H} / {W},
    drawnTop: {dy0/H:.4f}, drawnH: {(dy1-dy0)/H:.4f}, drawnW: {(dx1-dx0)/W:.4f},
    keysBottom: {(ky1+8)/H:.4f},   // just under the d-pad; anything lower crops off
    screenH: {h/H:.4f},            // the screen aperture, as a fraction of the art
  }};
{JEND}"""
    jtxt = JS.read_text(encoding="utf-8")
    must(jtxt.count(JSTART) == 1 and jtxt.count(JEND) == 1,
         f"art markers not found exactly once in {JS.name}")
    JS.write_text(jtxt[:jtxt.index(JSTART)] + jblock + jtxt[jtxt.index(JEND) + len(JEND):],
                  encoding="utf-8")
    print(f"  art box: drawn y {dy0}..{dy1}, x {dx0}..{dx1} -> {JS.name}")

    print(f"  traced {len(ap)} points from {ART.name} ({W}x{H})")
    print(f"  OK circle: {100*kcx/W:.2f}% / {100*kcy/H:.2f}%  ({kw}x{kh}px) -> {KEYCSS.name}")
    print(f"  aperture: left={100*x/W:.2f}% top={100*y/H:.2f}% "
          f"width={100*w/W:.2f}% height={100*h/H:.2f}%  ({w}x{h}px)")
    print(f"  wrote {CSS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
