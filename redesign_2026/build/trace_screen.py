#!/usr/bin/env python3
"""
Trace the screen aperture out of assets/flipphone.png and write it into
build/parts/18_quiz.css as a clip-path.

The handset art is hand-drawn: the screen opening is a wobbly quadrilateral,
not a rectangle. The CSS used to approximate it with a plain box, which sat
slightly inside the ink and left a hairline of yellow between the screen fill
and the drawn stroke. This measures the real opening instead.

How it works: the art is black strokes on transparency, and the screen is a
hole in it. So the aperture is simply the transparent region you land in if
you start in the middle of the screen -- no guessing, no eyeballing.

Run after changing assets/flipphone.png:

    python3 build/trace_screen.py && python3 build/build.py

Needs PIL, numpy, cv2 (all already used elsewhere in this build).
"""
import sys, pathlib
import numpy as np
from PIL import Image
import cv2

ROOT  = pathlib.Path(__file__).resolve().parent.parent
ART   = ROOT / "assets" / "flipphone.png"
CSS   = ROOT / "build" / "parts" / "18_quiz.css"
START = "  /* >>> screen-shape: generated by build/trace_screen.py, do not hand-edit */"
END   = "  /* <<< screen-shape */"
EPS   = 1.0   # px of contour simplification: keeps the wobble, drops the jaggies


def must(cond, msg):
    if not cond:
        sys.exit("TRACE FAILED: " + msg)


def main():
    must(ART.exists(), f"{ART} missing")
    im = Image.open(ART).convert("RGBA")
    W, H = im.size
    alpha = np.array(im)[..., 3]

    # every non-ink pixel; the screen hole is one connected piece of this
    holes = (alpha <= 128).astype(np.uint8)
    n, lab = cv2.connectedComponents(holes, connectivity=4)
    must(n > 2, "no enclosed regions found - is the art still line-on-transparent?")

    # seed in the middle of the upper half, where the screen is
    sy, sx = int(H * 0.255), int(W * 0.50)
    rid = int(lab[sy, sx])
    must(rid != 0, "seed point landed on ink, not inside the screen")

    # the region must not touch the border, or we've flood-filled the background
    mask = (lab == rid).astype(np.uint8)
    touches = mask[0, :].any() or mask[-1, :].any() or mask[:, 0].any() or mask[:, -1].any()
    must(not touches, "traced region reaches the image edge - that's the background, not the screen")

    # close any speckles inside the aperture so the outline is a single loop
    ff = mask.copy()
    pad = np.zeros((H + 2, W + 2), np.uint8)
    cv2.floodFill(ff, pad, (0, 0), 1)          # fill from outside the shape
    mask = mask | (1 - ff)                      # anything unreached was an interior hole

    cnts, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    must(len(cnts) >= 1, "no contour")
    c = max(cnts, key=cv2.contourArea)

    x, y, w, h = cv2.boundingRect(c)
    frac = (w * h) / float(W * H)
    must(0.02 < frac < 0.25, f"aperture is {frac:.1%} of the art - that doesn't look like a screen")

    ap = cv2.approxPolyDP(c, EPS, True).reshape(-1, 2)
    must(len(ap) >= 4, "simplified to fewer than 4 points")

    # the element is the aperture's bounding box; clip-path points are % of it
    pts = [((px - x) / w * 100.0, (py - y) / h * 100.0) for px, py in ap]
    # every vertex is comma-separated; the line breaks are only for readability.
    # (joining a group of vertices with spaces instead makes the whole polygon
    # invalid and the browser silently computes clip-path:none.)
    vert = [f"{u:.2f}% {v:.2f}%" for u, v in pts]
    poly = ",\n      ".join(", ".join(vert[i:i + 4]) for i in range(0, len(vert), 4))

    block = f"""{START}
  /* {len(ap)} points traced from the {W}x{H} art at {EPS}px tolerance.
     The box is the aperture's exact bounding box; the clip-path follows the
     inside of the drawn stroke, so the screen fill stops where the ink starts
     instead of leaving a gap. */
  .phone-frame .pf-screen{{
    position:absolute; z-index:1;
    left:{100*x/W:.2f}%; top:{100*y/H:.2f}%; width:{100*w/W:.2f}%; height:{100*h/H:.2f}%;
    background:var(--yellow); overflow:hidden;
    box-shadow:inset 0 0 5px rgba(0,0,0,.35);
    clip-path:polygon(
      {poly}
    );
  }}
{END}"""

    css = CSS.read_text(encoding="utf-8")
    must(css.count(START) == 1 and css.count(END) == 1,
         f"markers not found exactly once in {CSS.name} - add them around the .pf-screen rule")
    head = css[:css.index(START)]
    tail = css[css.index(END) + len(END):]
    CSS.write_text(head + block + tail, encoding="utf-8")

    print(f"  traced {len(ap)} points from {ART.name} ({W}x{H})")
    print(f"  aperture: left={100*x/W:.2f}% top={100*y/H:.2f}% "
          f"width={100*w/W:.2f}% height={100*h/H:.2f}%  ({w}x{h}px)")
    print(f"  wrote {CSS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
